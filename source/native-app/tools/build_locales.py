"""Validate public UI catalogs and compile a shared UTF-8 string/offset table.

Every selectable locale must cover core.json; missing advanced text falls back
to the canonical English keys. No network translation is used.
"""
import argparse
import json
import re
from pathlib import Path

PRINTF = re.compile(r'%(?:[1-9][0-9]*\$)?[-+#0 ]*(?:[0-9]+|\*)?(?:\.(?:[0-9]+|\*))?(?:hh|ll|[hljztL])?[diuoxXfFeEgGaAcspn%]')
NAMED = re.compile(r'\{[a-z_][a-z_0-9]*\}')

def unique_object(pairs):
    out = {}
    for key, value in pairs:
        if key in out:
            raise ValueError('duplicate JSON key: ' + key)
        out[key] = value
    return out

def read(path):
    return json.loads(path.read_text(encoding='utf-8'), object_pairs_hook=unique_object)

def compile_catalogs(directory):
    languages = read(directory / 'languages.json')
    keys = read(directory / 'en.json')['strings']
    core = read(directory / 'core.json')['strings']
    if not keys or len(keys) != len(set(keys)) or any(not isinstance(k, str) or not k for k in keys):
        raise ValueError('English keys must be unique, nonempty strings')
    if not core or len(core) != len(set(core)) or not set(core) <= set(keys):
        raise ValueError('core keys must be unique English keys')
    if not 2 <= len(languages) <= 32 or languages[0]['code'] != 'en':
        raise ValueError('English must be the first of 2–32 languages')
    if len({l['code'] for l in languages}) != len(languages):
        raise ValueError('duplicate locale')
    keys = sorted(keys)
    blob = bytearray(b'\0')
    offsets = {}
    def intern(s):
        if s not in offsets:
            offsets[s] = len(blob)
            blob.extend(s.encode('utf-8') + b'\0')
        return offsets[s]
    key_offsets = [intern(k) for k in keys]
    rows, metadata, statistics = [], [], {}
    for locale in languages:
        code = locale['code']
        if not re.fullmatch(r'[a-z]{2}(?:-[A-Z]{2}|-[A-Z][a-z]{3})?', code) or locale['direction'] not in ('ltr', 'rtl'):
            raise ValueError('invalid locale metadata: ' + code)
        if not isinstance(locale['nativeName'], str) or not locale['nativeName'] or len(locale['nativeName'])>64 or any(ord(c)<32 for c in locale['nativeName']):
            raise ValueError('invalid native language name: ' + code)
        if not re.fullmatch(r'[a-z]{2}(?:-[A-Z]{2})?', locale['metadataLanguage']):
            raise ValueError('invalid metadata language: ' + code)
        strings = dict.fromkeys(keys, None) if code == 'en' else read(directory / (code + '.json'))['strings']
        if not isinstance(strings, dict) or not set(strings) <= set(keys):
            raise ValueError('unknown translation keys: ' + code)
        if not set(core) <= set(strings):
            raise ValueError('missing core translations: ' + code)
        if code != 'en':
            catalog = read(directory / (code + '.json'))
            if catalog['sourceLanguage'] != 'en' or catalog['targetLanguage'] != code:
                raise ValueError('catalog language mismatch: ' + code)
        for key in keys:
            if code != 'en' and key not in strings:
                continue
            value = strings[key] if code != 'en' else key
            if not isinstance(value, str) or not value or '\0' in key + value:
                raise ValueError('empty/non-string/NUL translation: ' + code + ': ' + key)
            if any(ord(c) < 32 and c not in '\n\t' for c in key + value):
                raise ValueError('control character: ' + code + ': ' + key)
            if any('\u202a' <= c <= '\u202e' or '\u2066' <= c <= '\u2069' for c in value):
                raise ValueError('hidden bidi control: ' + code + ': ' + key)
            if any(token.endswith('n') for token in PRINTF.findall(value)) or PRINTF.findall(key) != PRINTF.findall(value) or NAMED.findall(key) != NAMED.findall(value):
                raise ValueError('placeholder mismatch: ' + code + ': ' + key)
            if len(value) > max(500, len(key) * 5):
                raise ValueError('translation too long: ' + code + ': ' + key)
        rows.append([0 if code == 'en' or k not in strings else intern(strings[k]) for k in keys])
        metadata.append('    {' + ','.join([json.dumps(code), json.dumps(locale['nativeName'], ensure_ascii=False), json.dumps(locale['metadataLanguage']), 'true' if locale['direction'] == 'rtl' else 'false', str(len(strings))]) + '},\n')
        statistics[code] = {'translated': len(strings), 'total': len(keys), 'core': len(core), 'coreComplete': True}
    if len(blob)>16<<20:
        raise ValueError('menu catalog exceeds the 16 MiB bundled text budget')
    # One byte string avoids constructing thousands of string_view entries in
    # every native translation unit. Offset 0 denotes English fallback.
    chunks = ['    "' + ''.join('\\%03o' % b for b in blob[n:n+64]) + '"\n' for n in range(0, len(blob), 64)]
    lines = ['// Generated by tools/build_locales.py; edit JSON catalogs.\n', 'inline constexpr Locale catalog_locales[]={\n', *metadata, '};\n', 'inline constexpr char text_blob[]=\n', *chunks, ';\n']
    lines.append('inline constexpr std::uint32_t key_offsets[]={' + ','.join(map(str, key_offsets)) + '};\n')
    lines.append('inline constexpr std::uint32_t value_offsets[][' + str(len(keys)) + ']={\n')
    lines.extend('    {' + ','.join(map(str, row)) + '},\n' for row in rows)
    lines.append('};\n')
    lines.append('inline constexpr std::uint32_t core_key_indices[]={' + ','.join(str(keys.index(k)) for k in sorted(core)) + '};\n')
    return ''.join(lines), statistics

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--directory', type=Path, default=Path(__file__).resolve().parent.parent / 'ui/locales')
    args = parser.parse_args()
    output, stats = compile_catalogs(args.directory)
    target = args.directory / 'catalogs.inc'
    if args.check:
        if not target.is_file() or target.read_text() != output:
            raise ValueError('translation table is stale; run tools/build_locales.py')
    else:
        target.write_text(output, encoding='utf-8')
    print('Menu catalogs: ' + ', '.join(code + ' ' + str(s['translated']) + '/' + str(s['total']) for code, s in stats.items()) + '; complete core and reproducible table')

if __name__ == '__main__':
    main()
