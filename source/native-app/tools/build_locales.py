"""Validate and compile the bundled application translation catalog."""
import argparse,json,re
from pathlib import Path
root=Path(__file__).resolve().parent.parent
p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
source=root/'ui/locales/de.json';catalog=json.loads(source.read_text())
assert catalog['sourceLanguage']=='en' and catalog['targetLanguage']=='de'
strings=catalog['strings'];assert len(strings)>900
placeholder=re.compile(r'%(?:[0-9]+\$)?[-+0-9.#]*[sdifux]|\{[a-z_]+\}')
for key,value in strings.items():
    assert isinstance(value,str) and value and '\0' not in key+value,key
    assert placeholder.findall(key)==placeholder.findall(value),key
    assert len(value)<=max(500,len(key)*4),key
rows='// Generated by tools/build_locales.py from de.json.\n'+''.join('    {'+json.dumps(k,ensure_ascii=False)+','+json.dumps(strings[k],ensure_ascii=False)+'},\n' for k in sorted(strings))
target=root/'ui/locales/de.inc'
if args.check:assert target.read_text()==rows,'translation table is stale'
else:target.write_text(rows)
print(f'German catalog: {len(strings)} entries, valid placeholders and reproducible bundled table')
